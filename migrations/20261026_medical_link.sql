ALTER TABLE paciente
  ALTER COLUMN id_medico DROP NOT NULL;

CREATE TABLE IF NOT EXISTS codigo_vinculo_medico (
  id_codigo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_medico INTEGER NOT NULL REFERENCES medico(id_usuario) ON DELETE CASCADE,
  codigo_hash CHAR(64) NOT NULL UNIQUE,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expira_em TIMESTAMPTZ NOT NULL,
  resgatado_em TIMESTAMPTZ,
  id_paciente INTEGER UNIQUE REFERENCES paciente(id_usuario) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_codigo_vinculo_medico
  ON codigo_vinculo_medico (id_medico);

CREATE INDEX IF NOT EXISTS idx_codigo_vinculo_expiracao
  ON codigo_vinculo_medico (expira_em)
  WHERE resgatado_em IS NULL;
