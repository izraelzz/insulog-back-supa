const assert = require('node:assert/strict')
const test = require('node:test')
const ExcelJS = require('exceljs')
const { montarDadosRelatorio } = require('../src/reports/relatorioData')
const { gerarXlsx } = require('../src/reports/xlsxReport')

test('XLSX mantém valores numéricos, aplicações, datas locais e filtros após estilização', async () => {
  const report = montarDadosRelatorio(require('./fixtures/relatorio-exemplo.json'), { dataInicio: '2026-08-01', dataFim: '2026-08-31' })
  const workbook = new ExcelJS.Workbook()
  await workbook.xlsx.load(await gerarXlsx(report))
  const resumo = workbook.getWorksheet('Resumo')
  const registros = workbook.getWorksheet('Registros')
  assert.equal(resumo.getCell('A6').value, report.resumo.media)
  assert.equal(resumo.getCell('C6').value, report.resumo.percentualAlvo / 100)
  assert.equal(resumo.getCell('E6').value, 48.5)
  assert.equal(resumo.getCell('G12').value, 0.5)
  assert.equal(resumo.getCell('G12').numFmt, '0.0%')
  assert.equal(registros.rowCount, 20)
  assert.equal(registros.getCell('A11').value.toISOString(), '2026-08-01T06:42:00.000Z')
  assert.equal(registros.getCell('B11').value, 48)
  assert.equal(registros.getCell('E11').value, null)
  assert.equal(registros.getCell('E14').value, 22)
  assert.equal(registros.getCell('F14').value, 'Rápida: 4 UI\nBasal: 18 UI')
  assert.equal(registros.getTable('RegistrosInsulog').table.autoFilterRef, 'A10:G20')
  assert.equal(registros.views[0].ySplit, 10)
  assert.equal(registros.views[0].showGridLines, false)
})


test('abre na lista completa e preserva registros, doses e observações em ordem cronológica', async () => {
  const report = montarDadosRelatorio(require('./fixtures/relatorio-exemplo.json'), { dataInicio: '2026-08-01', dataFim: '2026-08-31' })
  const esperados = structuredClone(report.registros)
  report.registros.reverse()
  report.registros[0].observacao = 'Observação detalhada. '.repeat(100)
  esperados.at(-1).observacao = report.registros[0].observacao
  const workbook = new ExcelJS.Workbook()
  await workbook.xlsx.load(await gerarXlsx(report))
  const folha = workbook.getWorksheet('Registros')
  assert.equal(workbook.worksheets[workbook.views[0].activeTab].name, 'Registros')
  assert.equal(workbook.getWorksheet('Resumo').getCell('A4').value.hyperlink, "#'Registros'!A10")
  assert.equal(folha.getCell('E8').value.hyperlink, "#'Resumo'!A1")
  assert.equal(folha.getTable('RegistrosInsulog').table.columns.every(coluna => coluna.filterButton), true)
  assert.equal(folha.rowCount - 10, esperados.length)
  for (const [indice, registro] of esperados.entries()) {
    const linha = folha.getRow(11 + indice)
    assert.equal(linha.getCell(1).value.toISOString().slice(0, 16), registro.dataHora.replace(' ', 'T').slice(0, 16))
    assert.equal(linha.getCell(2).value, registro.glicose)
    assert.equal(linha.getCell(3).value, registro.classificacao)
    assert.equal(linha.getCell(4).value, registro.periodo)
    assert.equal(linha.getCell(5).value, registro.insulinas.length ? registro.totalInsulina : null)
    assert.equal(linha.getCell(6).value, registro.insulinas.map(item => `${item.tipo}: ${item.unidades} UI`).join('\n') || '—')
    assert.equal(linha.getCell(7).value, registro.observacao || '—')
  }
  assert.equal(report.registros[0].id, esperados.at(-1).id, 'exportação não deve reordenar os dados de entrada')
})
